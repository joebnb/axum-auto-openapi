//! A small users API demonstrating automatic OpenAPI generation.
//!
//! Run with:
//!
//! ```text
//! cargo run --example basic
//! curl http://127.0.0.1:3000/users/42
//! curl http://127.0.0.1:3000/api/openapi
//! ```

use axum::extract::{Path, Query};
use axum::http::StatusCode;
use axum::Json;
use axum_openapi::routing::get;
use axum_openapi::{ApiKeyLocation, Info, Router, SecurityScheme, Server, Tag};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, JsonSchema)]
struct User {
    id: u64,
    name: String,
}

#[derive(Clone, Debug, Deserialize, JsonSchema)]
struct CreateUser {
    /// Display name. Must not be empty.
    name: String,
}

#[derive(Clone, Debug, Deserialize, JsonSchema)]
struct UserQuery {
    /// Include the user's organizations in the response.
    #[serde(default)]
    include_orgs: bool,
}

async fn list_users(Query(query): Query<UserQuery>) -> Json<Vec<User>> {
    let users = vec![User {
        id: 1,
        name: if query.include_orgs {
            "Ada (acme)".to_owned()
        } else {
            "Ada".to_owned()
        },
    }];
    Json(users)
}

async fn get_user(Path(id): Path<u64>) -> Result<Json<User>, StatusCode> {
    if id == 0 {
        return Err(StatusCode::NOT_FOUND);
    }
    Ok(Json(User {
        id,
        name: "Ada".to_owned(),
    }))
}

async fn create_user(Json(input): Json<CreateUser>) -> Json<User> {
    Json(User {
        id: 42,
        name: input.name,
    })
}

#[tokio::main]
async fn main() {
    let api = Router::<()>::new()
        .info(
            Info::new("Users API", "0.1.0")
                .description("A tiny example generated by `axum-openapi`."),
        )
        .server(Server::new("http://127.0.0.1:3000").description("Local development"))
        .tag(Tag::new("users").description("User management"))
        .security_scheme("bearer", SecurityScheme::bearer())
        .security_scheme(
            "api_key",
            SecurityScheme::api_key("X-API-Key", ApiKeyLocation::Header),
        )
        .route(
            "/users",
            get(list_users)
                .summary("List users")
                .tag("users")
                .post(create_user)
                .summary("Create a user")
                .tag("users")
                .security("bearer"),
        )
        .route(
            "/users/{id}",
            get(get_user)
                .summary("Fetch a user")
                .description("Returns 404 when the user does not exist.")
                .tag("users")
                .security("bearer")
                .response::<User>(200)
                .empty_response(404, "Not Found"),
        );
    // The document and Swagger UI are published automatically at
    // `/api/openapi` and `/api/docs`; call `.documentation(false)` to
    // withhold them or `.openapi_json_route(..)` / `.swagger_ui(..)` to
    // change the paths.

    let (app, document) = api.finish();

    println!("{}", document.to_json_pretty());

    let listener = tokio::net::TcpListener::bind("127.0.0.1:3000")
        .await
        .expect("bind 127.0.0.1:3000");
    println!("listening on http://127.0.0.1:3000");
    println!("OpenAPI JSON: http://127.0.0.1:3000/api/openapi");

    axum::serve(listener, app).await.expect("server error");
}
